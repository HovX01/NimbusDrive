const PROVIDERS = {
  tiktok: {
    label: "TikTok browser session",
    loginUrl: "https://www.tiktok.com/login",
    domains: [".tiktok.com", "www.tiktok.com", "tiktok.com"],
    authCookies: ["sessionid", "sid_tt", "uid_tt", "odin_tt"],
  },
  instagram: {
    label: "Instagram browser session",
    loginUrl: "https://www.instagram.com/accounts/login/",
    domains: [".instagram.com", "www.instagram.com", "instagram.com"],
    authCookies: ["sessionid", "ds_user_id"],
  },
  facebook: {
    label: "Facebook browser session",
    loginUrl: "https://www.facebook.com/login/",
    domains: [".facebook.com", "www.facebook.com", "facebook.com"],
    authCookies: ["c_user", "xs"],
  },
};

chrome.runtime.onMessage.addListener((message, _sender, sendResponse) => {
  if (!message || message.type !== "NIMBUS_SOCIAL_CONNECT") return false;
  connect(message.provider)
    .then((response) => sendResponse(response))
    .catch((error) => sendResponse({ ok: false, error: error.message || String(error) }));
  return true;
});

async function connect(providerName) {
  const provider = PROVIDERS[providerName];
  if (!provider) throw new Error("Unsupported social provider.");

  await chrome.tabs.create({ url: provider.loginUrl, active: true });
  const cookies = await waitForSessionCookies(provider);
  return {
    ok: true,
    provider: providerName,
    label: provider.label,
    cookies: toNetscapeCookieJar(cookies),
  };
}

async function waitForSessionCookies(provider) {
  const deadline = Date.now() + 5 * 60 * 1000;
  let lastCookies = [];

  while (Date.now() < deadline) {
    lastCookies = await getProviderCookies(provider);
    if (hasAuthCookie(provider, lastCookies)) return lastCookies;
    await delay(1500);
  }

  if (lastCookies.length > 0) return lastCookies;
  throw new Error("No logged-in session was found. Finish login in the opened tab, then click Connect again.");
}

async function getProviderCookies(provider) {
  const byKey = new Map();
  for (const domain of provider.domains) {
    const cookies = await chrome.cookies.getAll({ domain });
    for (const cookie of cookies) {
      byKey.set(`${cookie.domain}\t${cookie.path}\t${cookie.name}`, cookie);
    }
  }
  return Array.from(byKey.values()).sort((a, b) => a.domain.localeCompare(b.domain) || a.name.localeCompare(b.name));
}

function hasAuthCookie(provider, cookies) {
  return cookies.some((cookie) => provider.authCookies.includes(cookie.name) && cookie.value);
}

function toNetscapeCookieJar(cookies) {
  const lines = [
    "# Netscape HTTP Cookie File",
    "# Generated by Nimbus Social Connector after an explicit Connect click.",
  ];

  for (const cookie of cookies) {
    const includeSubdomains = cookie.domain.startsWith(".") ? "TRUE" : "FALSE";
    const secure = cookie.secure ? "TRUE" : "FALSE";
    const expires = Math.floor(cookie.expirationDate || 0);
    lines.push([cookie.domain, includeSubdomains, cookie.path || "/", secure, String(expires), cookie.name, cookie.value].join("\t"));
  }

  return `${lines.join("\n")}\n`;
}

function delay(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
